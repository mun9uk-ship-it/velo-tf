/**
 * Velo Tf — builds every Terraform file from the current state.
 *
 * state = {
 *   resources: [{ id, fields }]
 * }
 */
const Generator = (() => {

  function buildResourceBlocks(state) {
    return state.resources.map(r => {
      const def = RESOURCES[r.id];
      if (!def) return "";
      return `# ${def.desc}\n${def.hcl(r.fields)}`;
    }).join("\n\n");
  }

  function buildMainTf(state) {
    const header = `# main.tf — generated by Velo Tf\n# Review before running: terraform init && terraform validate\n\n`;
    return header + buildResourceBlocks(state) + "\n";
  }

  function buildVariablesTf() {
    return `# variables.tf — generated by Velo Tf\n# Add input variables here to parameterize your configuration.\n\n`;
  }

  function buildOutputsTf(state) {
    const lines = ["# outputs.tf — generated by Velo Tf"];

    const rp = state.resources.find(r => r.id === "random_password");
    if (rp) {
      lines.push(
        `output "password" {`,
        `  value     = random_password.${rp.fields.name}.result`,
        `  sensitive = true`,
        `}`
      );
    }

    const lf = state.resources.find(r => r.id === "local_file");
    if (lf) {
      lines.push(
        `output "file_path" {`,
        `  value = local_file.${lf.fields.name}.filename`,
        `}`
      );
    }

    return lines.join("\n") + "\n";
  }

  function buildProvidersTf(state) {
    const providers = [...new Set(
      state.resources.map(r => RESOURCES[r.id].provider)
    )];

    if (providers.length === 0) {
      return `# providers.tf — generated by Velo Tf\n# No providers yet. Add a resource to populate this file.\n`;
    }

    const blocks = providers.map(p =>
      `    ${p} = {\n      source = "hashicorp/${p}"\n    }`
    ).join("\n");

    return `# providers.tf — generated by Velo Tf\n\nterraform {\n  required_providers {\n${blocks}\n  }\n}\n`;
  }

  function buildReadme(state) {
    const list = state.resources.length
      ? state.resources.map(r => `- **${RESOURCES[r.id].label}** — ${RESOURCES[r.id].desc}`).join("\n")
      : "- (none yet)";

    return `# Velo Tf Configuration\n\nGenerated with Velo Tf.\n\n## Resources\n${list}\n\n## Usage\n\n\`\`\`bash\nterraform init\nterraform validate\nterraform plan\nterraform apply\n\`\`\`\n\n## Notes\nGenerated for learning. Review every line before applying.\n`;
  }

  function validate(state) {
    const errors = [];
    const warnings = [];

    state.resources.forEach(r => {
      const def = RESOURCES[r.id];
      def.fields.forEach(f => {
        if (f.type === "text" && (!r.fields[f.name] || String(r.fields[f.name]).trim() === "")) {
          errors.push(`${def.label}: "${f.label}" is empty.`);
        }
      });
    });

    if (state.resources.length === 0) {
      warnings.push("Add at least one resource to generate files.");
    }
    if (state.resources.some(r => r.id === "null_resource")) {
      warnings.push("null_resource is usually a trigger — pair it with a provisioner.");
    }

    return { errors, warnings };
  }

  function buildAll(state) {
    return {
      "main.tf":      buildMainTf(state),
      "variables.tf": buildVariablesTf(state),
      "outputs.tf":   buildOutputsTf(state),
      "providers.tf": buildProvidersTf(state),
      "README.md":    buildReadme(state)
    };
  }

  return { buildAll, validate };
})();