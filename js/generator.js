/**
 * Velo TerraForm — builds every Terraform file from the current state.
 */
const Generator = (() => {

  function buildResourceBlocks(state) {
    return state.resources.map(r => {
      const def = RESOURCES[r.id];
      if (!def) return "";
      return `# ${def.desc}\n${def.hcl(r.fields)}`;
    }).join("\n\n");
  }

  function buildMainTf(state) {
    const header = `# main.tf — generated by Velo TerraForm\n# Review before running: terraform init && terraform validate\n\n`;
    return header + buildResourceBlocks(state) + "\n";
  }

  function buildVariablesTf() {
    return `# variables.tf — generated by Velo TerraForm\n# Add input variables here to parameterize your configuration.\n\n`;
  }

  function buildOutputsTf(state) {
    const lines = ["# outputs.tf — generated by Velo TerraForm"];
    
    // توليد مخرجات لكل الموارد التي أضافها المستخدم
    state.resources.forEach((r, index) => {
      const def = RESOURCES[r.id];
      const resName = r.fields.name || def.id + "_" + index;

      if (r.id === "random_password") {
        lines.push(`output "${resName}_password" {\n  value     = random_password.${resName}.result\n  sensitive = true\n}`);
      } 
      else if (r.id === "local_file") {
        lines.push(`output "${resName}_file_path" {\n  value = local_file.${resName}.filename\n}`);
      }
      else if (r.id === "time_static") {
        lines.push(`output "${resName}_timestamp" {\n  value = time_static.${resName}.rfc3339\n}`);
      }
      else if (r.id === "tls_private_key") {
        lines.push(`output "${resName}_private_key" {\n  value     = tls_private_key.${resName}.private_key_pem\n  sensitive = true\n}`);
      }
    });

    return lines.join("\n\n") + "\n";
  }

  function buildProvidersTf(state) {
    const providers = [...new Set(
      state.resources.map(r => RESOURCES[r.id].provider)
    )];

    if (providers.length === 0) {
      return `# providers.tf — generated by Velo TerraForm\n# No providers yet.\n`;
    }

    const blocks = providers.map(p => {
      let source = `hashicorp/${p}`;
      return `    ${p} = {\n      source = "${source}"\n    }`;
    }).join("\n");

    return `# providers.tf — generated by Velo TerraForm\n\nterraform {\n  required_providers {\n${blocks}\n  }\n}\n`;
  }

  function buildReadme(state) {
    const list = state.resources.length
      ? state.resources.map(r => `- **${RESOURCES[r.id].label}** — ${RESOURCES[r.id].desc}`).join("\n")
      : "- (none yet)";

    return `# Velo TerraForm Configuration\n\nGenerated with Velo TerraForm.\n\n## Resources\n${list}\n\n## Usage\n\n\`\`\`bash\nterraform init\nterraform validate\nterraform plan\nterraform apply\n\`\`\`\n\n## Notes\nGenerated for learning. Review every line before applying.\n`;
  }

  function validate(state) {
    const errors = [];
    const warnings = [];

    state.resources.forEach(r => {
      const def = RESOURCES[r.id];
      def.fields.forEach(f => {
        if (f.type === "text" && (!r.fields[f.name] || String(r.fields[f.name]).trim() === "")) {
          errors.push(`${def.label}: "${f.label}" is empty.`);
        }
      });
    });

    if (state.resources.length === 0) {
      warnings.push("Add at least one resource to generate files.");
    }
    if (state.resources.some(r => r.id === "null_resource")) {
      warnings.push("null_resource is usually a trigger — pair it with a provisioner.");
    }

    return { errors, warnings };
  }

  function buildAll(state) {
    return {
      "main.tf":      buildMainTf(state),
      "variables.tf": buildVariablesTf(state),
      "outputs.tf":   buildOutputsTf(state),
      "providers.tf": buildProvidersTf(state),
      "README.md":    buildReadme(state)
    };
  }

  return { buildAll, validate };
})();